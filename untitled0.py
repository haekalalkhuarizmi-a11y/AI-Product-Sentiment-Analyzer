def analisis_sentimen_gemma(ulasan_produk):

    if not ulasan_produk.strip():
        return "Silakan masukkan ulasan produk terlebih dahulu."

    # Membuat instruksi untuk Gemma
    prompt = f"""
    Kamu adalah seorang analis data e-commerce.

    Tugasmu adalah menganalisis ulasan produk berikut.

    Tentukan salah satu kategori sentimen:
    1. POSITIF
    2. NEGATIF
    3. NETRAL

    Berikan alasan singkat berdasarkan isi ulasan.

    Gunakan format jawaban berikut:

    SENTIMEN: [POSITIF/NEGATIF/NETRAL]

    ALASAN:
    [Penjelasan singkat]

    ULASAN PRODUK:
    {ulasan_produk}
    """

    # Mengubah prompt menjadi format percakapan Gemma
    messages = [
        {"role": "user", "content": prompt}
    ]

    input_ids = tokenizer.apply_chat_template(
        messages,
        add_generation_prompt=True,
        return_tensors="pt"
    ).to(model.device)

    # Memproses ulasan menggunakan Gemma
    with torch.no_grad():
        outputs = model.generate(
            input_ids,
            max_new_tokens=150,
            do_sample=False
        )

    # Mengambil hasil jawaban AI
    hasil = tokenizer.decode(
        outputs[0][input_ids.shape[-1]:],
        skip_special_tokens=True
    )

    return hasil

import torch
import traceback

# Fungsi analisis sentimen menggunakan Gemma
def analisis_sentimen_gemma(ulasan_produk):

    try:
        if not ulasan_produk or not ulasan_produk.strip():
            return "Silakan masukkan ulasan produk terlebih dahulu."

        prompt = f"""
Kamu adalah analis sentimen produk e-commerce.

Analisis ulasan berikut dan tentukan satu kategori:
POSITIF, NEGATIF, atau NETRAL.

Berikan alasan singkat berdasarkan isi ulasan.

Gunakan format:
SENTIMEN: [kategori]
ALASAN: [alasan]

ULASAN:
{ulasan_produk}

HASIL ANALISIS:
"""

        # Mengubah teks menjadi token
        inputs = tokenizer(
            prompt,
            return_tensors="pt"
        )

        # Memindahkan input ke perangkat model
        device = next(model.parameters()).device
        inputs = inputs.to(device)

        # Menjalankan Gemma
        with torch.inference_mode():
            outputs = model.generate(
                **inputs,
                max_new_tokens=120,
                do_sample=False,
                pad_token_id=tokenizer.eos_token_id
            )

        # Mengambil jawaban AI saja
        jawaban = tokenizer.decode(
            outputs[0][inputs["input_ids"].shape[-1]:],
            skip_special_tokens=True
        )

        return jawaban.strip()

    except Exception as e:
        print("DETAIL ERROR:")
        traceback.print_exc()
        return f"Terjadi kesalahan: {type(e).__name__}: {str(e)}"


